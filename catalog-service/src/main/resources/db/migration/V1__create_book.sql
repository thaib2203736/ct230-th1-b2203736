-- catalog-service: lược đồ ban đầu (Flyway quản lý, Hibernate chỉ validate)
CREATE TABLE book (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn            VARCHAR(13)    NOT NULL UNIQUE CHECK (isbn ~ '^97[89][0-9]{10}$'),
    title           VARCHAR(255)   NOT NULL,
    author          VARCHAR(255)   NOT NULL,
    author_id       BIGINT,
    published_year  INTEGER,
    price_amount    NUMERIC(15, 2) NOT NULL CHECK (price_amount >= 0),
    price_currency  VARCHAR(3)     NOT NULL CHECK (price_currency IN ('VND', 'USD')),
    version         BIGINT         NOT NULL DEFAULT 0,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE INDEX idx_book_title ON book (lower(title));
